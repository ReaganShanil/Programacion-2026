# Escriba aquí su juego Adivina el número.
import random

numero_secreto = random.randint(1, 20)
intentos = 0

print('Bienvenido al juego: Adivina el número(frío o caliente)')
print('Intenta adivinar el número secreto entre 1 y 20!')

while True:
    intento = int(input("Intento: "))

    intentos += 1

    if intento == numero_secreto:
        print(f"El número es correcto! Adivinaste en {intentos} intentos.")
        break

    if numero_secreto > intento:
        direccion = "El número secreto es mayor."
    else:
        direccion = "El número secreto es menor."

    distancia = abs(numero_secreto - intento)

    if distancia <= 2:
        temperatura = "hirviendo: estás muy cerca del número."
    elif distancia <= 5:
        temperatura = "caliente: te estás acercando."
    elif distancia <= 10:
        temperatura = "tibio: vas por buen camino"
    else:
        temperatura = "frío: estás lejos."

    print(f"{direccion} Pista: {temperatura}\n")

